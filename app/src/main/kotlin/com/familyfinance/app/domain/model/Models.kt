package com.familyfinance.app.domain.model

import com.familyfinance.app.core.money.Money

/**
 * An authenticated person. One account per human — a shared family login is explicitly not
 * supported, because ownership of financial records is derived from the authenticated identity.
 */
data class UserProfile(
    val uid: String,
    val email: String,
    val displayName: String,
    val photoUrl: String? = null,
    val familyId: String? = null,
    val role: Role = Role.MEMBER,
    val status: MemberStatus = MemberStatus.ACTIVE,
    val createdAt: Long = 0L,
    val updatedAt: Long = 0L,
)

/** The private, person-level profile. Never readable by other members through the app. */
data class MemberProfile(
    val uid: String,
    val familyId: String,
    val fullName: String,
    val photoUrl: String? = null,
    val dateOfBirthEpochDay: Long? = null,
    val mobile: String? = null,
    val email: String? = null,
    val relationship: String? = null,
    val occupation: String? = null,
    val notes: String? = null,
    /** Non-financial profile sharing toggle. Financial data stays private regardless. */
    val shareProfileWithFamily: Boolean = true,
    val updatedAt: Long = 0L,
)

data class Family(
    val id: String,
    val name: String,
    val photoUrl: String? = null,
    val currencyCode: String = "BDT",
    val timezone: String = "Asia/Dhaka",
    val ownerUid: String,
    val createdAt: Long = 0L,
    /** Feature flag: family net-worth tile on the common dashboard. */
    val netWorthEnabled: Boolean = false,
)

/**
 * A family member as seen in the member directory: the shareable profile plus the membership
 * metadata (role, status). Contains no financial field of any kind.
 */
data class FamilyMemberView(
    val profile: MemberProfile,
    val role: Role,
    val status: MemberStatus,
) {
    val uid: String get() = profile.uid
    val fullName: String get() = profile.fullName
    val isActive: Boolean get() = status == MemberStatus.ACTIVE
}

data class FamilyInvitation(
    val id: String,
    val familyId: String,
    /** Short human-typable code, e.g. "HSN-7Q4K". */
    val code: String,
    val createdByUid: String,
    val createdAt: Long,
    val expiresAt: Long,
    val revokedAt: Long? = null,
    val maxUses: Int = 1,
    val usedCount: Int = 0,
    val invitedEmail: String? = null,
) {
    fun isRedeemable(now: Long = System.currentTimeMillis()): Boolean =
        revokedAt == null && now < expiresAt && usedCount < maxUses
}

/** A bank / MFS / cash / card / investment account. Always owned by exactly one member. */
data class Account(
    val id: String,
    val ownerUid: String,
    val familyId: String,
    val name: String,
    val type: AccountType,
    val institution: String? = null,
    /** Full identifier. Stored encrypted at rest and **never** rendered in full. */
    val identifier: String? = null,
    /** Only the last four characters are ever shown in the UI. */
    val last4: String? = null,
    val openingBalance: Money = Money.ZERO,
    val currencyCode: String = "BDT",
    val isActive: Boolean = true,
    val notes: String? = null,
    val createdAt: Long = 0L,
    val updatedAt: Long = 0L,
    val syncState: SyncState = SyncState.SYNCED,
)

/** A single financial movement. Owned implicitly by the authenticated user — there is no
 *  "paid by" / "income by" field anywhere in the model. */
data class Transaction(
    val id: String,
    /** Device-generated idempotency key. Guarantees an offline replay cannot double-post. */
    val clientId: String,
    val ownerUid: String,
    val familyId: String,
    val type: TransactionType,
    val amount: Money,
    val categoryId: String? = null,
    val subCategoryId: String? = null,
    val accountId: String? = null,
    val transferFromAccountId: String? = null,
    val transferToAccountId: String? = null,
    /** Calendar date, stored as epoch-day so it is timezone-stable. */
    val dateEpochDay: Long,
    val note: String = "",
    val attachmentIds: List<String> = emptyList(),
    val recurringRuleId: String? = null,
    /** Set when this row was generated by a recurring rule, to prevent duplicate generation. */
    val recurrenceOccurrenceEpochDay: Long? = null,
    val createdAt: Long = 0L,
    val updatedAt: Long = 0L,
    val syncState: SyncState = SyncState.SYNCED,
)

/** A recurring income/expense/transfer template. */
data class RecurringRule(
    val id: String,
    val ownerUid: String,
    val familyId: String,
    val type: TransactionType,
    val amount: Money,
    val categoryId: String? = null,
    val subCategoryId: String? = null,
    val accountId: String? = null,
    val transferFromAccountId: String? = null,
    val transferToAccountId: String? = null,
    val note: String = "",
    val frequency: RecurrenceFrequency,
    /** For [RecurrenceFrequency.CUSTOM]: every N days. */
    val customIntervalDays: Int? = null,
    val startEpochDay: Long,
    val endEpochDay: Long? = null,
    /** Last occurrence already materialised into a [Transaction]. */
    val lastGeneratedEpochDay: Long? = null,
    val isActive: Boolean = true,
    val reminderEnabled: Boolean = true,
    val createdAt: Long = 0L,
    val updatedAt: Long = 0L,
)

data class Attachment(
    val id: String,
    val ownerUid: String,
    val familyId: String,
    val transactionId: String? = null,
    val fileName: String,
    val mimeType: String,
    val sizeBytes: Long,
    val storagePath: String,
    val isFamilyVisible: Boolean = false,
    val createdAt: Long = 0L,
)
